export const LANG_COOKIE = "nb-lang";

export function isLang(v: unknown): v is Lang {
  return v === "zh" || v === "en";
}

export function t(lang: Lang, key: DictKey): string {
  return (lang === "en" ? en : zh)[key] ?? zh[key];
}

/** Translate outside React using the language cookie current at call time. */
export function currentT(key: DictKey): string {
  return t(currentLanguage(), key);
}

export function currentLanguage(): Lang {
  if (typeof document === "undefined") return "en";
  const match = document.cookie.match(/(?:^|;\s*)nb-lang=([^;]+)/);
  return match && isLang(match[1]) ? match[1] : "en";
}
